def guide(key: str) -> str:
    path = Path(__file__).with_name("guides.json")
    if path.exists():
        try:
            custom = json.loads(path.read_text(encoding="utf-8"))
            if custom.get(key):
                return custom[key]
        except (ValueError, OSError):
            pass
    return DEFAULTS[key]
